// WithREST serves every method that carries a google.api.http annotation as
// a REST route on the HTTP port, next to gRPC and Connect:
//
//	rpc GetNote(GetNoteRequest) returns (GetNoteResponse) {
//	  option (google.api.http) = {get: "/v1/notes/{id}"};
//	}
//
//	gs := grpcmux.NewServer(grpcmux.WithREST())   // or apis.rest: true
//	notev1.RegisterNoteServiceServer(gs, impl)    // GET /v1/notes/{id} is live
//
// The routes are built from the protobuf descriptors when a service is
// registered ([Server.RegisterService], i.e. the generated
// pb.RegisterXxxServer(gs, impl), or [RegisterConnectService]); there is no
// generated gateway code and no per-service registration call. Methods
// without an annotation are not affected.
//
// A REST call is the same call as on the other protocols:
//
//   - it runs behind the HTTP middleware (CORS, request ID, access log,
//     authentication, rate limiting) and through the same interceptor chain
//     as the Connect bridge (authz policy, validation, metrics, deadlines,
//     custom interceptors, recovery; see [WithoutHTTPInterceptors]);
//   - auth exemptions ([WithNoAuthMethods], [WithNoAuthPrefixes]), rate-limit
//     rules and deadlines are looked up by the RPC's full method
//     ("/pkg.Service/Method"), whatever its REST path is, and the access log's
//     action is that full method too;
//   - path variables, query parameters, body, response_body, PATCH field
//     masks and additional_bindings follow the google.api.http rules as
//     grpc-gateway implements them; JSON follows the server's naming setting;
//   - errors are the JSON error body of [mux.WriteHTTPErrorResponse] with the
//     HTTP status of the code, and the error details (google.rpc.ErrorInfo,
//     BadRequest, RetryInfo, ...) with their "@type": WithREST implies
//     [WithTypedErrorDetails] for the whole HTTP port of this server;
//   - a server-streaming method answers with newline-delimited JSON, one
//     {"result": ...} object per message; an error after the first message
//     is a final {"error": ...} object. Client-streaming and bidirectional
//     methods have no REST form and are skipped.
//
// Routes generated by protoc-gen-grpc-gateway and registered on
// [Server.ServeMux] keep working; do not register the same service both ways.
func WithREST() Option {
	return func(o *options) {
		o.platform.rest = true
	}
}

// restRoute is one HTTP binding of a method.
type restRoute struct {
	s          *Server
	impl       any
	fullMethod string
	httpMethod string
	template   string
	input      protoreflect.MessageDescriptor

	bodyAll   bool                         // body: "*"
	bodyField protoreflect.FieldDescriptor // body: "<field>"
	maskField protoreflect.FieldDescriptor // FieldMask to derive from a PATCH body
	respField protoreflect.FieldDescriptor // response_body: "<field>"
	// filter lists the fields bound from the path and the body: query
	// parameters must not overwrite them.
	filter *utilities.DoubleArray

	unary  *grpc.MethodDesc
	stream *grpc.StreamDesc
}

// restMatch carries the route the middleware resolved to the dispatcher.
type restMatch struct {
	route  *restRoute
	params map[string]string
	// notAllowed is set when the path is a REST path but not for this HTTP
	// method.
	notAllowed bool
}

type restMatchKey struct{}

func restMatchFrom(ctx context.Context) *restMatch {
	m, _ := ctx.Value(restMatchKey{}).(*restMatch)
	return m
}

// rpcMethodOf returns the full method of the RPC a request is for: the
// resolved REST route's, otherwise the URL path (which is the full method for
// Connect, gRPC and gRPC-Web requests).
func rpcMethodOf(r *http.Request) string {
	if m := restMatchFrom(r.Context()); m != nil && m.route != nil {
		return m.route.fullMethod
	}
	return r.URL.Path
}

// registerREST adds the REST routes of a service; a no-op without WithREST
// and for services without google.api.http annotations.
func (s *Server) registerREST(desc *grpc.ServiceDesc, impl any) {
	if !s.opts.platform.rest {
		return
	}
	d, err := protoregistry.GlobalFiles.FindDescriptorByName(protoreflect.FullName(desc.ServiceName))
	sd, ok := d.(protoreflect.ServiceDescriptor)
	if err != nil || !ok {
		s.Logger.Log(s.ctx, logging.LevelWarn, "rest: no protobuf descriptor for "+desc.ServiceName+", no REST routes")
		return
	}
	for i := range desc.Methods {
		m := &desc.Methods[i]
		s.addRESTRoutes(sd, m.MethodName, restRoute{
			s: s, impl: impl, fullMethod: "/" + desc.ServiceName + "/" + m.MethodName, unary: m,
		})
	}
	for i := range desc.Streams {
		st := &desc.Streams[i]
		rt := restRoute{s: s, impl: impl, fullMethod: "/" + desc.ServiceName + "/" + st.StreamName, stream: st}
		if st.ClientStreams {
			if md := sd.Methods().ByName(protoreflect.Name(st.StreamName)); md != nil && httpRule(md) != nil {
				s.Logger.Log(s.ctx, logging.LevelWarn,
					"rest: "+rt.fullMethod+" streams requests; it has no REST form and its google.api.http rule is ignored")
			}
			continue
		}
		s.addRESTRoutes(sd, st.StreamName, rt)
	}
}

func httpRule(md protoreflect.MethodDescriptor) *annotations.HttpRule {
	rule, _ := proto.GetExtension(md.Options(), annotations.E_Http).(*annotations.HttpRule)
	return rule
}

// addRESTRoutes registers the bindings of one method. An annotation that
// cannot be served (unknown body field, bad path template) is a programming
// error and panics at registration, like a bad net/http pattern.
func (s *Server) addRESTRoutes(sd protoreflect.ServiceDescriptor, method string, base restRoute) {
	md := sd.Methods().ByName(protoreflect.Name(method))
	if md == nil {
		return
	}
	rule := httpRule(md)
	if rule == nil {
		return
	}
	base.input = md.Input()
	for _, binding := range append([]*annotations.HttpRule{rule}, rule.GetAdditionalBindings()...) {
		rt := base
		if err := rt.bind(binding, md); err != nil {
			panic(fmt.Sprintf("grpcmux: google.api.http rule of %s: %v", base.fullMethod, err))
		}
		if s.restRouter == nil {
			s.restRouter = runtime.NewServeMux(
				// The middleware already applied X-HTTP-Method-Override, and
				// the POST-as-GET form fallback would consume the body here.
				runtime.WithDisableHTTPMethodOverride(),
				runtime.WithDisablePathLengthFallback(),
				runtime.WithRoutingErrorHandler(func(ctx context.Context, _ *runtime.ServeMux, _ runtime.Marshaler,
					_ http.ResponseWriter, _ *http.Request, httpStatus int,
				) {
					if m := restMatchFrom(ctx); m != nil && httpStatus == http.StatusMethodNotAllowed {
						m.notAllowed = true
					}
				}),
			)
		}
		route := &rt
		err := s.restRouter.HandlePath(rt.httpMethod, rt.template,
			func(_ http.ResponseWriter, r *http.Request, params map[string]string) {
				if m := restMatchFrom(r.Context()); m != nil {
					m.route, m.params = route, params
				}
			})
		if err != nil {
			panic(fmt.Sprintf("grpcmux: google.api.http rule of %s: %v", base.fullMethod, err))
		}
		s.Logger.Log(s.ctx, logging.LevelDebug, "rest", "path", rt.httpMethod+" "+rt.template, "method", rt.fullMethod)
	}
}

// bind fills the route from one HttpRule.
func (rt *restRoute) bind(rule *annotations.HttpRule, md protoreflect.MethodDescriptor) error {
	switch p := rule.GetPattern().(type) {
	case *annotations.HttpRule_Get:
		rt.httpMethod, rt.template = http.MethodGet, p.Get
	case *annotations.HttpRule_Put:
		rt.httpMethod, rt.template = http.MethodPut, p.Put
	case *annotations.HttpRule_Post:
		rt.httpMethod, rt.template = http.MethodPost, p.Post
	case *annotations.HttpRule_Delete:
		rt.httpMethod, rt.template = http.MethodDelete, p.Delete
	case *annotations.HttpRule_Patch:
		rt.httpMethod, rt.template = http.MethodPatch, p.Patch
	case *annotations.HttpRule_Custom:
		rt.httpMethod, rt.template = strings.ToUpper(p.Custom.GetKind()), p.Custom.GetPath()
	default:
		return errors.New("no HTTP method and path")
	}
	fields := md.Input().Fields()
	var bound [][]string
	switch body := rule.GetBody(); body {
	case "":
	case "*":
		rt.bodyAll = true
	default:
		rt.bodyField = fields.ByName(protoreflect.Name(body))
		if rt.bodyField == nil {
			return fmt.Errorf("body %q is not a field of %s", body, md.Input().FullName())
		}
		bound = append(bound, []string{body})
		// PATCH with a message body and exactly one FieldMask field: an
		// absent mask means "the fields present in the body" (AIP-134), as in
		// grpc-gateway.
		if rt.httpMethod == http.MethodPatch && rt.bodyField.Message() != nil && !rt.bodyField.IsList() && !rt.bodyField.IsMap() {
			rt.maskField = soleFieldMask(fields)
		}
	}
	if rb := rule.GetResponseBody(); rb != "" {
		rt.respField = md.Output().Fields().ByName(protoreflect.Name(rb))
		if rt.respField == nil {
			return fmt.Errorf("response_body %q is not a field of %s", rb, md.Output().FullName())
		}
	}
	for _, v := range templateVariables(rt.template) {
		bound = append(bound, strings.Split(v, "."))
	}
	rt.filter = utilities.NewDoubleArray(bound)
	return nil
}

// soleFieldMask returns the FieldMask field of a message when it has exactly
// one.
func soleFieldMask(fields protoreflect.FieldDescriptors) protoreflect.FieldDescriptor {
	var found protoreflect.FieldDescriptor
	for i := range fields.Len() {
		f := fields.Get(i)
		if f.Message() != nil && f.Message().FullName() == "google.protobuf.FieldMask" && !f.IsList() {
			if found != nil {
				return nil
			}
			found = f
		}
	}
	return found
}

// templateVariables returns the field paths bound by a path template:
// "/v1/{parent=shelves/*}/books/{book.id}" yields parent and book.id.
func templateVariables(template string) []string {
	var vars []string
	for {
		_, rest, ok := strings.Cut(template, "{")
		if !ok {
			return vars
		}
		v, after, ok := strings.Cut(rest, "}")
		if !ok {
			return vars
		}
		name, _, _ := strings.Cut(v, "=")
		vars = append(vars, strings.TrimSpace(name))
		template = after
	}
}

// resolveREST is the middleware's route resolver: it matches the request
// against the REST routes once and returns the request carrying the match,
// plus the RPC's full method ("" when the request is not a REST call).
func (s *Server) resolveREST(r *http.Request) (*http.Request, string) {
	if s.restRouter == nil {
		return r, ""
	}
	m := &restMatch{}
	r = r.WithContext(context.WithValue(r.Context(), restMatchKey{}, m))
	s.restRouter.ServeHTTP(discardResponse{}, r)
	if m.route == nil {
		return r, ""
	}
	// Resolution must agree with dispatch. Handlers registered with Handle
	// (and the Connect procedures) are served ahead of the REST routes, so a
	// path that one of them owns is not a REST call, even when a REST
	// template also matches it: it must not inherit the RPC's auth exemption
	// or rate-limit rule.
	if s.httpServerMux != nil {
		if _, pattern := s.httpServerMux.Handler(r); pattern != "" && pattern != "/" {
			m.route, m.params = nil, nil
			return r, ""
		}
	}
	return r, m.route.fullMethod
}

// discardResponse is the writer the router matches against; routing writes
// nothing.
type discardResponse struct{}

func (discardResponse) Header() http.Header         { return http.Header{} }
func (discardResponse) Write(b []byte) (int, error) { return len(b), nil }
func (discardResponse) WriteHeader(int)             {}

// restOrGateway dispatches a request to its resolved REST route, otherwise to
// the grpc-gateway mux (generated gateway routes, HandleFunc routes, 404).
func (s *Server) restOrGateway() http.Handler {
	gw := s.mux.ServeMux()
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		m := restMatchFrom(r.Context())
		switch {
		case m != nil && m.route != nil && m.route.unary != nil:
			m.route.serveUnary(w, r, m.params)
		case m != nil && m.route != nil:
			m.route.serveStream(w, r, m.params)
		case m != nil && m.notAllowed:
			// The path is a REST path, but not for this HTTP method. Routes
			// on the gateway mux (generated gateway code, HandleFunc, a
			// catch-all) come first; only when none of them takes the
			// request either is it "method not allowed" rather than
			// "not found".
			gw.ServeHTTP(w, r.WithContext(mux.MarkMethodNotAllowed(r.Context())))
		default:
			gw.ServeHTTP(w, r)
		}
	})
}

// prepare annotates the context like a gateway route (RPC method for the
// access log, request body logging, Grpc-Timeout) and reads the body.
func (rt *restRoute) prepare(r *http.Request) (context.Context, []byte, error) {
	ctx, err := runtime.AnnotateIncomingContext(r.Context(), rt.s.ServeMux(), r, rt.fullMethod,
		runtime.WithHTTPPathPattern(rt.template))
	if err != nil {
		return r.Context(), nil, err
	}
	if rt.bodyField == nil && !rt.bodyAll {
		return ctx, nil, nil
	}
	body, st := readLimited(r.Body, rt.s.opts.maxRequestBodyBytes)
	if st != nil {
		return ctx, nil, st.Err()
	}
	return ctx, body, nil
}

func (rt *restRoute) serveUnary(w http.ResponseWriter, r *http.Request, params map[string]string) {
	gw := rt.s.ServeMux()
	inbound, outbound := runtime.MarshalerForRequest(gw, r)
	ctx, body, err := rt.prepare(r)
	if err != nil {
		runtime.HTTPError(ctx, gw, outbound, w, r, err)
		return
	}
	dec := func(v any) error { return rt.decode(inbound, r, body, params, v) }
	resp, stream, err := rt.s.invokeUnary(ctx, r, rt.impl, rt.fullMethod, *rt.unary, dec)
	header, trailer := stream.metadata()
	ctx = runtime.NewServerMetadataContext(ctx, runtime.ServerMetadata{HeaderMD: header, TrailerMD: trailer})
	if err != nil {
		runtime.HTTPError(ctx, gw, outbound, w, r, contextError(ctx, err))
		return
	}
	runtime.ForwardResponseMessage(ctx, gw, outbound, w, r, rt.responseBody(resp), gw.GetForwardResponseOptions()...)
}

// contextError turns an error without a gRPC status into the status of the
// context's own error (DEADLINE_EXCEEDED, CANCELED), as the gRPC server does.
func contextError(ctx context.Context, err error) error {
	if ctxErr := ctx.Err(); ctxErr != nil && status.Code(err) == codes.Unknown {
		return status.FromContextError(ctxErr).Err()
	}
	return err
}

// decode binds body, path variables and query parameters into the request
// message, in the order grpc-gateway's generated code does.
func (rt *restRoute) decode(inbound runtime.Marshaler, r *http.Request, body []byte,
	params map[string]string, v any,
) error {
	msg, ok := v.(proto.Message)
	if !ok {
		return status.Errorf(codes.Internal, "request type %T is not a proto.Message", v)
	}
	if err := rt.decodeBody(inbound, body, msg); err != nil {
		return invalidArgument(err)
	}
	for name, value := range params {
		if err := runtime.PopulateFieldFromPath(msg, name, value); err != nil {
			return status.Errorf(codes.InvalidArgument, "type mismatch, parameter: %s, error: %v", name, err)
		}
	}
	if rt.bodyAll {
		return nil // every field comes from the body or the path
	}
	if err := runtime.PopulateQueryParameters(msg, r.URL.Query(), rt.filter); err != nil {
		return status.Errorf(codes.InvalidArgument, "%v", err)
	}
	return nil
}

func (rt *restRoute) decodeBody(inbound runtime.Marshaler, body []byte, msg proto.Message) error {
	if len(bytes.TrimSpace(body)) == 0 {
		return nil
	}
	switch {
	case rt.bodyAll:
		return decodeJSON(inbound, body, msg)
	case rt.bodyField == nil:
		return nil
	}
	m := msg.ProtoReflect()
	fd := rt.bodyField
	if fd.Message() == nil || fd.IsList() || fd.IsMap() {
		// A scalar, repeated or map body: decode it as that field of the
		// request message.
		wrapped := make([]byte, 0, len(body)+len(fd.JSONName())+6)
		wrapped = append(wrapped, `{"`...)
		wrapped = append(wrapped, fd.JSONName()...)
		wrapped = append(wrapped, `":`...)
		wrapped = append(wrapped, body...)
		wrapped = append(wrapped, '}')
		return protojson.UnmarshalOptions{DiscardUnknown: true}.Unmarshal(wrapped, msg)
	}
	sub := m.NewField(fd).Message()
	if err := decodeJSON(inbound, body, sub.Interface()); err != nil {
		return err
	}
	m.Set(fd, protoreflect.ValueOfMessage(sub))
	if rt.maskField != nil && maskIsEmpty(m.Get(rt.maskField).Message()) {
		mask := &fieldmaskpb.FieldMask{Paths: fieldMaskFromBody(body, fd.Message())}
		m.Set(rt.maskField, protoreflect.ValueOfMessage(mask.ProtoReflect()))
	}
	return nil
}

func decodeJSON(inbound runtime.Marshaler, body []byte, msg proto.Message) error {
	if err := inbound.NewDecoder(bytes.NewReader(body)).Decode(msg); err != nil && !errors.Is(err, io.EOF) {
		return err
	}
	return nil
}

// fieldMaskFromBody derives the FieldMask of a PATCH from its JSON body: the
// fields of md that the body sets, as proto field names (AIP-134: an absent
// mask means "what the body carries").
//
// A member the message does not declare contributes nothing, at any depth.
// The decoder ignores such members everywhere (REST and Connect bodies
// alike), and the mask has to agree with it: a client built against a newer
// schema must be able to PATCH an older server. The rules for declared
// fields are grpc-gateway's:
//
//   - a member is found by proto name or JSON name; the path uses the proto
//     name;
//   - a singular message field whose value is a non-empty object is descended
//     into, so {"address":{"city":"x"}} yields address.city;
//   - everything else is a leaf and yields its own path: scalars, null, empty
//     objects, repeated and map fields (never descended into), well-known
//     types written as scalars, and google.protobuf.Any;
//   - google.protobuf.Struct and Value hold free-form JSON, so their object
//     keys are path segments as they are.
//
// It never fails: body has already been decoded into the message, which is
// where malformed JSON and type mismatches are reported.
func fieldMaskFromBody(body []byte, md protoreflect.MessageDescriptor) []string {
	var root any
	if err := json.Unmarshal(body, &root); err != nil {
		return nil
	}
	obj, ok := root.(map[string]any)
	if !ok {
		return nil
	}
	seen := map[string]bool{}
	var paths []string
	add := func(path string) {
		if !seen[path] {
			seen[path] = true
			paths = append(paths, path)
		}
	}
	var walk func(prefix string, obj map[string]any, md protoreflect.MessageDescriptor)
	var free func(prefix string, v any)
	free = func(prefix string, v any) {
		m, ok := v.(map[string]any)
		if !ok || len(m) == 0 {
			add(prefix)
			return
		}
		for k, child := range m {
			free(prefix+"."+k, child)
		}
	}
	walk = func(prefix string, obj map[string]any, md protoreflect.MessageDescriptor) {
		fields := md.Fields()
		for key, value := range obj {
			fd := fields.ByName(protoreflect.Name(key))
			if fd == nil {
				fd = fields.ByJSONName(key)
			}
			if fd == nil {
				continue // not a field of this message: ignored, like the decoder does
			}
			path := string(fd.Name())
			if prefix != "" {
				path = prefix + "." + path
			}
			child, isObject := value.(map[string]any)
			sub := fd.Message()
			switch {
			case fd.IsList() || fd.IsMap() || sub == nil || !isObject || len(child) == 0:
				add(path)
			case sub.FullName() == "google.protobuf.Struct" || sub.FullName() == "google.protobuf.Value":
				free(path, value)
			case sub.FullName() == "google.protobuf.Any":
				add(path)
			default:
				// Only what is declared inside counts. An object holding
				// nothing but undeclared members yields no path: naming the
				// field itself would tell the service to replace it with an
				// empty message because of a member it does not know.
				walk(path, child, sub)
			}
		}
	}
	walk("", obj, md)
	slices.Sort(paths)
	return paths
}

func maskIsEmpty(mask protoreflect.Message) bool {
	paths := mask.Descriptor().Fields().ByName("paths")
	return paths == nil || mask.Get(paths).List().Len() == 0
}

// responseBody applies response_body: the named field is the HTTP response.
func (rt *restRoute) responseBody(resp proto.Message) proto.Message {
	if rt.respField == nil {
		return resp
	}
	v := resp.ProtoReflect().Get(rt.respField)
	var body any
	switch fd := rt.respField; {
	case fd.IsMap():
		out := map[string]any{}
		v.Map().Range(func(k protoreflect.MapKey, mv protoreflect.Value) bool {
			out[k.String()] = plainValue(fd.MapValue(), mv)
			return true
		})
		body = out
	case fd.IsList() && fd.Message() != nil:
		list := v.List()
		out := make([]proto.Message, list.Len())
		for i := range out {
			out[i] = list.Get(i).Message().Interface()
		}
		body = out
	case fd.IsList():
		list := v.List()
		out := make([]any, list.Len())
		for i := range out {
			out[i] = plainValue(fd, list.Get(i))
		}
		body = out
	default:
		body = plainValue(fd, v)
	}
	return restResponse{Message: resp, body: body}
}

func plainValue(fd protoreflect.FieldDescriptor, v protoreflect.Value) any {
	switch {
	case fd.Message() != nil:
		return v.Message().Interface()
	case fd.Enum() != nil:
		if ev := fd.Enum().Values().ByNumber(v.Enum()); ev != nil {
			return string(ev.Name())
		}
		return int32(v.Enum())
	}
	return v.Interface()
}

// restResponse makes grpc-gateway marshal body instead of the whole message
// (the interface its generated response wrappers implement).
type restResponse struct {
	proto.Message
	body any
}

// XXX_ResponseBody is the method grpc-gateway looks for.
//
//nolint:revive // the name is grpc-gateway's contract
func (r restResponse) XXX_ResponseBody() any { return r.body }
